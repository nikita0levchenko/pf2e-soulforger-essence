import {readFile, writeFile, mkdir} from "node:fs/promises";
import {fileURLToPath} from "node:url";

const catalogs = Object.fromEntries(await Promise.all(["en", "ru"].map(async (locale) =>
  [locale, JSON.parse(await readFile(new URL(`./lang/${locale}.json`, import.meta.url), "utf8"))])));
await writeFile(new URL("./scripts/translations.mjs", import.meta.url),
  `// Generated by build.mjs from lang/en.json and lang/ru.json.\nexport const TRANSLATIONS = ${JSON.stringify(catalogs, null, 2)};\n`);
const {itemTemplates, IDS} = await import("./scripts/core.mjs");
const {withLanguage} = await import("./scripts/i18n.mjs");

const destination = new URL("./items/", import.meta.url);
await mkdir(destination, {recursive: true});
const filenames = {
  [IDS.feat]: "fvtt-Item-manifest-essence-form.json",
  [IDS.flaw]: "fvtt-Item-apply-corruption-flaw.json",
  [IDS.essenceCarrier]: "fvtt-Item-essence-selection-effect.json",
  [IDS.flawCarrier]: "fvtt-Item-corruption-selection-effect.json"
};
for (const item of withLanguage("en", itemTemplates)) {
  item._stats = {systemId: "pf2e", systemVersion: "8.6.1", coreVersion: "14.369"};
  const target = new URL(filenames[item._id], destination);
  await writeFile(target, JSON.stringify(item, null, 2) + "\n");
  console.log(fileURLToPath(target));
}
